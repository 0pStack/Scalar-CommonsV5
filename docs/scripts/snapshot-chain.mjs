#!/usr/bin/env node
/**
 * Snapshot the runtime-defined surface of a live Scalar Commons node into
 * `docs/.chain/snapshot.json`.
 *
 * Why this exists: issue #73 requires that "documented values must match the
 * runtime, verified against the live node". Prose alone cannot carry that
 * guarantee — the moment a runtime constant changes, the docs silently rot. So
 * the numbers are read off a live node once, committed as a machine-readable
 * snapshot with provenance, and then `check-chain-values.mjs` (wired into
 * `npm run lint`) asserts every documented raw value still matches the
 * snapshot. That keeps the lint gate deterministic and offline while making the
 * live-node verification auditable and repeatable.
 *
 * Only *runtime-defined* facts are captured: pallet indices, pallet constants,
 * the extrinsic and storage surface, chain properties, runtime API method
 * signatures and the RPC method list. Volatile chain state (issuance, era
 * number, balances) is deliberately not snapshotted — documenting it would
 * guarantee it goes stale.
 *
 * Usage:
 *   npm run snapshot:chain                     # ws://127.0.0.1:9944
 *   npm run snapshot:chain -- ws://host:9944
 */
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { ApiPromise, WsProvider } from '@polkadot/api'

const HERE = dirname(fileURLToPath(import.meta.url))
const OUT = resolve(HERE, '..', '.chain', 'snapshot.json')

const endpoint = process.argv[2] ?? 'ws://127.0.0.1:9944'

const provider = new WsProvider(endpoint)
provider.on('error', () => {
  /* surfaced by the ApiPromise.create rejection below; no double-reporting */
})

let api
try {
  api = await ApiPromise.create({ provider, noInitWarn: true, throwOnConnect: true })
} catch (err) {
  console.error(`✗ cannot reach a Scalar Commons node at ${endpoint}`)
  console.error(`  ${err instanceof Error ? err.message : String(err)}`)
  console.error('  Start the devnet first — see docs/guide/run-a-node.md.')
  process.exit(1)
}

const meta = api.runtimeMetadata.asLatest
const header = await api.rpc.chain.getHeader()

/** Pallet name → `construct_runtime` index. Append-only by repo rule. */
const pallets = Object.fromEntries(
  meta.pallets
    .map((p) => [p.name.toString(), p.index.toNumber()])
    .sort((a, b) => a[1] - b[1]),
)

/** Pallet → constant name → raw on-chain value, as a decimal/JSON string. */
const consts = {}
for (const palletName of Object.keys(api.consts).sort()) {
  const entries = {}
  for (const constName of Object.keys(api.consts[palletName]).sort()) {
    entries[constName] = api.consts[palletName][constName].toString()
  }
  consts[palletName] = entries
}

/** Pallet → extrinsic name → `name(arg: Type, …)` call signature. */
const extrinsics = {}
for (const palletName of Object.keys(api.tx).sort()) {
  const entries = {}
  for (const callName of Object.keys(api.tx[palletName]).sort()) {
    const args = api.tx[palletName][callName].meta.args
      .map((a) => `${a.name.toString()}: ${a.type.toString()}`)
      .join(', ')
    entries[callName] = `${callName}(${args})`
  }
  extrinsics[palletName] = entries
}

/** Pallet → sorted storage entry names, i.e. the readable state surface. */
const storage = Object.fromEntries(
  Object.keys(api.query)
    .sort()
    .map((palletName) => [palletName, Object.keys(api.query[palletName]).sort()]),
)

/** Runtime API name → `method(arg: Type, …) -> Type` signatures. */
const typeName = (id) => meta.lookup.getTypeDef(id).type
const runtimeApis = {}
if (api.runtimeMetadata.version >= 15) {
  for (const a of api.runtimeMetadata.asV15.apis) {
    runtimeApis[a.name.toString()] = a.methods.map((m) => {
      const args = m.inputs.map((i) => `${i.name.toString()}: ${typeName(i.type)}`).join(', ')
      return `${m.name.toString()}(${args}) -> ${typeName(m.output)}`
    })
  }
}

const snapshot = {
  $comment:
    'Generated by docs/scripts/snapshot-chain.mjs from a live node. Do not hand-edit — re-run `npm run snapshot:chain`.',
  provenance: {
    endpoint,
    capturedAtBlock: header.number.toNumber(),
    capturedAtBlockHash: header.hash.toHex(),
    genesisHash: api.genesisHash.toHex(),
    nodeVersion: (await api.rpc.system.version()).toString(),
  },
  chain: {
    name: (await api.rpc.system.chain()).toString(),
    nodeName: (await api.rpc.system.name()).toString(),
    chainType: (await api.rpc.system.chainType()).toString(),
  },
  runtime: {
    specName: api.runtimeVersion.specName.toString(),
    implName: api.runtimeVersion.implName.toString(),
    specVersion: api.runtimeVersion.specVersion.toNumber(),
    transactionVersion: api.runtimeVersion.transactionVersion.toNumber(),
    metadataVersion: api.runtimeMetadata.version,
  },
  properties: {
    ss58Format: api.registry.chainSS58,
    tokenDecimals: api.registry.chainDecimals[0],
    tokenSymbol: api.registry.chainTokens[0],
  },
  pallets,
  consts,
  extrinsics,
  storage,
  runtimeApis,
  rpcMethods: (await api.rpc.rpc.methods()).methods.map((m) => m.toString()).sort(),
}

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(OUT, `${JSON.stringify(snapshot, null, 1)}\n`)

console.log(`✓ snapshot written to ${OUT}`)
console.log(
  `  ${snapshot.chain.name} — ${snapshot.runtime.specName} spec ${snapshot.runtime.specVersion} @ #${snapshot.provenance.capturedAtBlock}`,
)
console.log(
  `  ${Object.keys(pallets).length} pallets, ` +
    `${Object.values(consts).reduce((n, c) => n + Object.keys(c).length, 0)} constants, ` +
    `${Object.values(extrinsics).reduce((n, c) => n + Object.keys(c).length, 0)} extrinsics, ` +
    `${Object.keys(runtimeApis).length} runtime APIs, ` +
    `${snapshot.rpcMethods.length} RPC methods`,
)

await api.disconnect()
